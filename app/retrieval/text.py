TOKEN = re.compile(r"[^\W_]+(?:[-.][^\W_]+)*", re.UNICODE)


def _stem(token: str) -> str:
    for suffix, replacement in [
        ("ies", "y"),
        ("ing", ""),
        ("ed", ""),
        ("ly", ""),
        ("es", ""),
        ("s", ""),
    ]:
        if token.endswith(suffix) and len(token) - len(suffix) >= 3:
            stem = token[: -len(suffix)] + replacement
            if suffix in ("ing", "ed") and len(stem) > 3 and stem[-1] == stem[-2]:
                stem = stem[:-1]
            return stem
    return token


def analyze(text: str) -> list[str]:
    result = []
    for token in TOKEN.findall(unicodedata.normalize("NFKC", text).lower()):
        identifier = "-" in token or "." in token or any(c.isdigit() for c in token)
        if token not in STOPWORDS:
            result.append(token if identifier else _stem(token))
        if "-" in token or "." in token:
            result.extend(part for part in re.split(r"[-.]", token) if part not in STOPWORDS)
    return result
